import re
import subprocess
import sys
from pathlib import Path


TASK_NAME = re.compile(rb'(g_task_set_name\s*\([^,\n]+,\s*")(?:Frida|Meshlink)\.')
TYPE_NAME = re.compile(
    rb'(\bg_(?:type_register_static(?:_simple)?|type_register_fundamental|enum_register_static|flags_register_static|'
    rb'boxed_type_register_static|pointer_type_register_static)\s*\([^;]*?")'
    rb'(?:Frida|Meshlink)([A-Z][A-Za-z0-9_]*")'
)
DBUS_PROXY = re.compile(
    rb'G_DEFINE_TYPE_EXTENDED \(((?:Frida|Meshlink)[A-Za-z0-9_]+Proxy), '
    rb'([a-z][a-z0-9_]+), G_TYPE_DBUS_PROXY,'
)
ERROR_DOMAIN = re.compile(
    rb'(\b(?:g_quark_from_static_string|g_dbus_error_register_error_domain)\s*\(\s*")'
    rb'(?:frida|meshlink)(-(?:[a-z0-9]+-)*error-quark")'
)
ENUM_VALUES = re.compile(
    rb'(static const G(?:Enum|Flags)Value values\[\]\s*=\s*\{)([^;]*)(\};)',
    re.DOTALL,
)
ENUM_VALUE_NAME = re.compile(rb'"(?:FRIDA|MESHLINK)_([A-Za-z0-9_]+)"')
SOURCE_LINE = re.compile(rb'(?m)^(#line\s+\d+\s+")([^"\r\n]+)("\r?$)')
VALA_DIAGNOSTIC_FUNCTION = re.compile(
    rb'(?m)^(#define _vala_(?:assert|return_if_fail|return_val_if_fail|warn_if_fail)\([^\n]+?)G_STRFUNC'
)
ABSTRACT_METHOD_DIAGNOSTIC = re.compile(rb"(does not implement abstract method )`frida_[a-z0-9_]+'")
GLIB_INCLUDE = re.compile(rb"(?m)^#include <glib(?:-object)?\.h>\r?\n")


def neutralize_task_names(source: bytes, runtime_prefix: bytes = b"Meshlink") -> bytes:
    return TASK_NAME.sub(lambda match: match[1] + runtime_prefix + b".", source)


def neutralize_source_locations(source: bytes) -> bytes:
    return SOURCE_LINE.sub(lambda match: match[1] + match[2].replace(b"frida", b"meshlink") + match[3], source)


def neutralize_diagnostics(source: bytes, runtime_prefix: bytes = b"Meshlink") -> bytes:
    label = runtime_prefix.lower()
    source = VALA_DIAGNOSTIC_FUNCTION.sub(lambda match: match[1] + b'"' + label + b'"', source)
    source = ABSTRACT_METHOD_DIAGNOSTIC.sub(rb'\g<1>from this interface', source)
    definition = b'#define G_STRFUNC "' + label + b'"'
    if b"generated by valac" in source[:128] and definition not in source:
        include = GLIB_INCLUDE.search(source)
        if include is not None:
            source = source[:include.end()] + b'#undef G_STRFUNC\n' + definition + b'\n' + source[include.end():]
    return source


def neutralize_runtime_types(source: bytes, runtime_prefix: bytes = b"Meshlink") -> bytes:
    source = TYPE_NAME.sub(lambda match: match[1] + runtime_prefix + match[2], source)
    source = ERROR_DOMAIN.sub(lambda match: match[1] + runtime_prefix.lower() + match[2], source)

    def rename_dbus_proxy(match: re.Match[bytes]) -> bytes:
        name = match[1]
        old_prefix = b"Frida" if name.startswith(b"Frida") else b"Meshlink"
        neutral_name = runtime_prefix + name[len(old_prefix):]
        aliases = b"typedef " + name + b" " + neutral_name + b";\n"
        aliases += b"typedef " + name + b"Class " + neutral_name + b"Class;\n"
        return aliases + match[0].replace(name, neutral_name, 1)

    source = DBUS_PROXY.sub(rename_dbus_proxy, source)

    def rename_values(match: re.Match[bytes]) -> bytes:
        values = ENUM_VALUE_NAME.sub(lambda item: b'"' + runtime_prefix.upper() + b'_' + item[1] + b'"', match[2])
        return match[1] + values + match[3]

    return ENUM_VALUES.sub(rename_values, source)


def output_directory(arguments: list[str]) -> Path | None:
    for index, argument in enumerate(arguments):
        if argument == "--directory":
            return Path(arguments[index + 1])
        if argument.startswith("--directory="):
            return Path(argument.partition("=")[2])
    return None


def neutralize_directory(directory: Path, runtime_prefix: bytes = b"Meshlink") -> None:
    for generated in directory.rglob("*.c"):
        source = generated.read_bytes()
        updated = neutralize_source_locations(
            neutralize_diagnostics(
                neutralize_runtime_types(
                    neutralize_task_names(source, runtime_prefix), runtime_prefix
                ),
                runtime_prefix,
            )
        )
        if updated != source:
            generated.write_bytes(updated)


def main() -> int:
    options = sys.argv[1:]
    runtime_prefix = b"Meshlink"
    if options and options[0].startswith("--runtime-prefix="):
        runtime_prefix = options.pop(0).partition("=")[2].encode("ascii")
        if re.fullmatch(rb"[A-Z][A-Za-z0-9]*", runtime_prefix) is None:
            raise ValueError("Invalid runtime type prefix")
    compiler, *arguments = options
    result = subprocess.run([compiler, *arguments], check=False)
    if result.returncode != 0 or "-C" not in arguments:
        return result.returncode

    directory = output_directory(arguments)
    if directory is not None:
        neutralize_directory(directory, runtime_prefix)
    return 0


if __name__ == "__main__":
    sys.exit(main())
